#!/usr/bin/env bash
# Regenerates requirements.lock. Run it after changing COMFYUI_REF (Dockerfile),
# the default TRELLIS2_REF (start.sh) or requirements.in. Needs uv: https://docs.astral.sh/uv/
set -euo pipefail
cd "$(dirname "$0")"
COMFYUI_REF="$(sed -n 's/^ARG COMFYUI_REF=//p' Dockerfile)"
TRELLIS2_REF="$(sed -n 's/^TRELLIS2_REF="\${TRELLIS2_REF:-\([0-9a-f]\{40\}\)}".*/\1/p' start.sh)"
[[ -n "$COMFYUI_REF" && -n "$TRELLIS2_REF" ]] || { echo "could not read COMFYUI_REF / TRELLIS2_REF"; exit 1; }
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
curl -fsSL "https://raw.githubusercontent.com/comfyanonymous/ComfyUI/$COMFYUI_REF/requirements.txt" -o "$tmp/comfyui.txt"
# meshlib is left out on purpose: each pod installs it at start (own license, see README)
curl -fsSL "https://raw.githubusercontent.com/visualbruno/ComfyUI-Trellis2/$TRELLIS2_REF/requirements.txt" \
  | grep -viE '^[[:space:]]*meshlib[[:space:]]*$' | sed -E 's/^rembg[[:space:]]*$/rembg[cpu]/' > "$tmp/trellis2.txt"
uv pip compile -q --no-header --python-version 3.13 --python-platform x86_64-manylinux_2_39 \
  requirements.in "$tmp/comfyui.txt" "$tmp/trellis2.txt" -o "$tmp/lock.txt"
{ echo "# Generated by lock.sh — ComfyUI $COMFYUI_REF + ComfyUI-Trellis2 ${TRELLIS2_REF:0:7} + requirements.in"
  echo "# Python 3.13 · linux x86_64 (Ubuntu 24.04). Don't edit by hand; edit requirements.in and rerun lock.sh."
  cat "$tmp/lock.txt"; } > requirements.lock
echo "requirements.lock: $(grep -cE '^[a-z0-9]' requirements.lock) packages (ComfyUI $COMFYUI_REF, Trellis2 ${TRELLIS2_REF:0:7})"
